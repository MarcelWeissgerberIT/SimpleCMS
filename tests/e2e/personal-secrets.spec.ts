import { test, expect, openApp, MOD } from './fixtures'
const PASSPHRASE = 'test-only vault passphrase 2026', TOKEN = 'test-only-atlas-personal-token-8Qw2'
test('personal vault encrypts storage, locks, rejects a wrong passphrase and reopens', async ({ page }) => {
  await page.clock.install()
  await openApp(page)
  await page.keyboard.press(`${MOD}+,`)
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('tab', { name: /My secrets/ }).click()
  const vault = dialog.getByTestId('personal-secrets')
  await vault.getByLabel(/New vault passphrase/).fill(PASSPHRASE)
  await vault.getByLabel('Repeat passphrase', { exact: true }).fill(PASSPHRASE)
  await vault.getByRole('button', { name: 'Create vault', exact: true }).click()
  await expect(vault.getByRole('button', { name: 'Lock now', exact: true })).toBeVisible()
  await vault.getByLabel(/Name ·/).fill('atlas-my-agent')
  await vault.getByLabel('Token', { exact: true }).fill(TOKEN)
  await vault.getByRole('button', { name: 'Save encrypted', exact: true }).click()
  await expect(vault.locator('li')).toContainText('atlas-my-agent')
  await expect(vault.getByLabel('Token', { exact: true })).toHaveValue('')
  const stored = await page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>((resolve, reject) => { const r = indexedDB.open('one-personal-secrets');r.onsuccess = () => resolve(r.result);r.onerror = () => reject(r.error) })
    return new Promise<string>((resolve, reject) => { const r = db.transaction('vault').objectStore('vault').getAll();r.onsuccess = () => { resolve(JSON.stringify(r.result));db.close() };r.onerror = () => reject(r.error) })
  })
  expect(stored).not.toContain(TOKEN);expect(stored).not.toContain(PASSPHRASE);expect(stored).not.toContain('atlas-my-agent')
  await vault.getByRole('button', { name: 'Lock now', exact: true }).click()
  await expect(vault.locator('li')).toHaveCount(0)
  await vault.getByLabel('Vault passphrase', { exact: true }).fill('wrong passphrase')
  await vault.getByRole('button', { name: 'Unlock', exact: true }).click()
  await expect(vault.getByRole('alert')).toContainText('Could not unlock')
  await vault.getByLabel('Vault passphrase', { exact: true }).fill(PASSPHRASE)
  await vault.getByRole('button', { name: 'Unlock', exact: true }).click()
  await expect(vault.locator('li')).toContainText('atlas-my-agent')
  await page.clock.fastForward(600_001)
  await expect(vault.locator('li')).toHaveCount(0)
  await vault.getByLabel('Vault passphrase', { exact: true }).fill(PASSPHRASE)
  await vault.getByRole('button', { name: 'Unlock', exact: true }).click()
  await expect(vault.locator('li')).toContainText('atlas-my-agent')
  await page.screenshot({ path: 'test-results/personal-secrets.png' })
})
