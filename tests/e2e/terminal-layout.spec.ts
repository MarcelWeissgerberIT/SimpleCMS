import {test,expect,openApp,createPage,gotoPage,wsEval,doc,para,MOD} from './fixtures'
import {mockAgent,call,say,setKey,terminal,prompt} from './helpers/terminal'
const gate=()=>{let release!:()=>void;const promise=new Promise<void>(r=>release=r);return {promise,release}}
test.beforeEach(async({page})=>{await page.route('**/api/config',r=>r.fulfill({json:{schema_min:6}}));await page.route('**/api/session',r=>r.fulfill({json:{}}))})

test('side layout keeps both surfaces usable, separates contexts and offers compact controls on phones',async({page,context},info)=>{
 await page.setViewportSize({width:1440,height:1000});await openApp(page);await setKey(page)
 const source=await createPage(page,{title:'Task source',content:doc(para('Inspect this source.'))})
 const other=await createPage(page,{title:'Next request page',content:doc(para('Work here meanwhile.'))})
 await gotoPage(page,source);const held=gate()
 const mock=await mockAgent(context,[call('read','read_page',{id:source}),async()=>{await held.promise;return say('Original source reviewed.')()}])
 try{
  await page.keyboard.press(`${MOD}+j`)
  await expect(terminal(page).getByRole('button',{name:'Work overview',exact:true})).toBeHidden()
  await terminal(page).getByRole('button',{name:'Settings and tools',exact:true}).click()
  await expect(terminal(page).getByRole('button',{name:'Work overview',exact:true})).toBeVisible()
  await terminal(page).getByRole('button',{name:'Settings and tools',exact:true}).click()
  await terminal(page).getByRole('button',{name:'Beside page',exact:true}).click()
  await prompt(page).fill('Read the source');await prompt(page).press('Enter');await expect.poll(()=>mock.bodies.length).toBe(2)
  await expect(terminal(page)).toHaveAttribute('data-side','true')
  const stage=await page.locator('.stage').boundingBox(),term=await terminal(page).boundingBox()
  expect(stage!.x+stage!.width).toBeLessThanOrEqual(term!.x+1);expect(stage!.width).toBeGreaterThan(380)
  await page.getByRole('treeitem').filter({hasText:'Next request page'}).last().click()
  await expect(page).toHaveURL(new RegExp('#/p/'+other+'$'));await expect(terminal(page)).toBeVisible()
  const current=terminal(page).getByRole('region',{name:'Current task',exact:true})
  await expect(current).toContainText('Task context: Task source')
  await expect(current).toContainText('Elapsed');await expect(current).toContainText('no new response yet')
  await expect(terminal(page).getByLabel('Next request context',{exact:true})).toContainText('Next request page')
  await page.locator('.ProseMirror[contenteditable=true]').first().click();await page.keyboard.type(' Working while AI runs.')
  await expect(page.locator('.ProseMirror').first()).toContainText('Working while AI runs.')
  await page.screenshot({path:info.outputPath('side-desktop.png')})
  await terminal(page).getByRole('button',{name:'Switch page',exact:true}).click()
  const palette=page.locator('.pal-scrim');await palette.getByRole('combobox').fill('Next request page');await palette.getByRole('option').filter({hasText:'Next request page'}).first().click()
  await expect(terminal(page)).toBeVisible();await expect(page).toHaveURL(new RegExp('#/p/'+other+'$'))
  await page.setViewportSize({width:390,height:900})
  await expect(terminal(page)).not.toHaveAttribute('data-side','true')
  expect((await terminal(page).locator('.term-head').boundingBox())!.height).toBeLessThan(100)
  expect(await terminal(page).evaluate(e=>e.scrollWidth<=e.clientWidth+1)).toBe(true)
  await terminal(page).screenshot({path:info.outputPath('compact-mobile.png')})
  held.release();await expect(current).toContainText('Completed')
  await page.keyboard.press(`${MOD}+k`);await palette.getByRole('combobox').fill('Task source');await palette.getByRole('option').filter({hasText:'Task source'}).first().click()
  await expect(terminal(page)).toHaveCount(0);await page.keyboard.press(`${MOD}+j`)
  await page.setViewportSize({width:1440,height:1000});await expect(terminal(page)).toHaveAttribute('data-side','true')
  await page.reload();await expect(page.locator('.ProseMirror').first()).toBeVisible();await page.keyboard.press(`${MOD}+j`);await expect(terminal(page)).toHaveAttribute('data-side','true')
  expect(mock.bodies).toHaveLength(2)
 }finally{held.release()}
})

test('resume preserves the reading position across page changes and background completion; result jump stays explicit',async({page,context})=>{
 await openApp(page);await setKey(page)
 const source=await createPage(page,{title:'Reader source',content:doc(para('Source.'))})
 const other=await createPage(page,{title:'Other work',content:doc(para('Continue here.'))});await gotoPage(page,source)
 const held=gate();const mock=await mockAgent(context,[say(Array.from({length:75},(_,i)=>`Paragraph ${i}: previous analysis.`).join('\n\n')),async()=>{await held.promise;return say('Second result complete.')()}])
 try{
  await page.keyboard.press(`${MOD}+j`);await prompt(page).fill('Long analysis');await prompt(page).press('Enter');await expect(terminal(page).locator('.term-head__status')).toHaveText('Done')
  await prompt(page).fill('Continue analysis');await prompt(page).press('Enter');await expect.poll(()=>mock.bodies.length).toBe(2)
  const scroll=terminal(page).locator('.term-scroll');await scroll.evaluate(e=>{e.scrollTop=1200;e.dispatchEvent(new Event('scroll'))})
  await expect(terminal(page).getByRole('button',{name:'Go to current work ↓'})).toBeVisible()
  const anchor=await scroll.evaluate(e=>{const y=e.getBoundingClientRect().top;const p=[...e.querySelectorAll('.term-answer p')].find(p=>p.getBoundingClientRect().top>=y)!;return {text:p.textContent!,offset:p.getBoundingClientRect().top-y}})
  await page.keyboard.press(`${MOD}+j`);await gotoPage(page,other);held.release()
  const dock=page.getByRole('region',{name:'Background AI task'});await expect(dock).toContainText('Result ready')
  await dock.getByRole('button',{name:'Return to task'}).click()
  await expect.poll(()=>scroll.evaluate((e,a)=>{const p=[...e.querySelectorAll('.term-answer p')].find(p=>p.textContent===a.text)!;return Math.abs(p.getBoundingClientRect().top-e.getBoundingClientRect().top-a.offset)},anchor)).toBeLessThan(5)
  await expect(scroll).toBeFocused();await expect(terminal(page).getByRole('button',{name:'New activity ↓'})).toBeVisible()
  await page.keyboard.press(`${MOD}+j`);await dock.getByRole('button',{name:'View result',exact:true}).click()
  await expect(terminal(page).locator('.term-turn[data-turn="2"] .term-answer')).toBeFocused()
  await expect(page).toHaveURL(new RegExp('#/p/'+other+'$'))
 }finally{held.release()}
})

test('background review action focuses proposals without applying them',async({page,context})=>{
 await openApp(page);await setKey(page)
 await mockAgent(context,[call('create','create_page',{title:'Proposed destination',markdown:'Review before saving.'}),say('A page is proposed.')])
 await page.keyboard.press(`${MOD}+j`);await prompt(page).fill('Prepare a new page');await prompt(page).press('Enter')
 await expect(terminal(page).locator('.term-head__status')).toHaveText('Done');await page.keyboard.press(`${MOD}+j`)
 const dock=page.getByRole('region',{name:'Background AI task'})
 await expect(dock.getByRole('button',{name:'View result',exact:true})).toBeVisible()
 await dock.getByRole('button',{name:'Review changes (1)',exact:true}).click()
 await expect(terminal(page).locator('.term-change[data-status="pending"]')).toBeFocused()
 expect(await wsEval(page,s=>Object.values(s.pages).some((p:any)=>p.title==='Proposed destination'))).toBe(false)
})
