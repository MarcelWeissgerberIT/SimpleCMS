import {test,expect,openApp,createPage,gotoPage,MOD} from './fixtures'
import {mockAgent,call,say,setKey,run,terminal,resultText} from './helpers/terminal'
const gap=(i:number)=>({kind:'implementation',target:`sop${i}.ts`,reason:'Not read',repo:'repo-1',snapshot:'snapshot-1'})
test('evidence continuation keeps source and remainder, refuses writes and never edits the page',async({page,context})=>{
 await openApp(page);await setKey(page)
 const original=await createPage(page,{title:'Evidence original'})
 const other=await createPage(page,{title:'Other page'})
 await gotoPage(page,original);await page.keyboard.press(`${MOD}+j`);await expect.poll(()=>page.evaluate(()=>!!(window as any).__oneTerm)).toBe(true)
 const mocked=await mockAgent(context,[
  call('gaps','report_evidence_gaps',{gaps:Array.from({length:7},(_,i)=>gap(i))}),say('Some evidence is still missing.'),
  call('read','read_page',{id:original}),
  call('illegal','create_page',{title:'Must not create',markdown:'forbidden'}),
  call('remaining','report_evidence_gaps',{gaps:[gap(2)]}),say('The current batch is partially checked; sop2.ts remains inaccessible.')
 ])
 await run(page,'Check requirements and prepare an Atlas sync')
 const card=terminal(page).getByRole('complementary',{name:'Open evidence review'}).last()
 await expect(card.getByText('7 open checks.',{exact:false})).toBeVisible()
 await expect(terminal(page).locator('.term-activity')).toContainText('Partial result')
 await gotoPage(page,other);await page.keyboard.press(`${MOD}+j`)
 await card.getByRole('button',{name:'Review missing evidence',exact:true}).click()
 await expect(card.getByText('3 open checks.',{exact:false})).toBeVisible({timeout:30000})
 const state=await page.evaluate(()=>(window as any).__oneTerm.state.getState())
 expect(state.turns.at(-1).context.pageId).toBe(original)
 expect(state.turns.at(-1).evidence.gaps.map((g:any)=>g.target)).toEqual(['sop5.ts','sop6.ts','sop2.ts'])
 expect(state.changes).toHaveLength(0)
 expect(state.turns.at(-1).contract.compiled.contract.read_only).toBe(true)
 expect(state.turns.at(-1).contract.compiled.contract.external_write).toBe(false)
 expect(state.turns.at(-1).contract.compiled.contract.execute).toBe(false)
 expect(resultText(mocked.bodies[4],'illegal')).toMatch(/read.only|not.*allow|refus|forbidden|boundary|bound|permission/i)
 await card.getByRole('button',{name:'Keep partial result'}).click()
 await expect(card).toContainText('Partial result kept')
 await expect.poll(()=>page.evaluate(async()=>new Promise<boolean>(resolve=>{const q=indexedDB.open('one-mcp-work');q.onsuccess=()=>{const db=q.result,r=db.transaction('records').objectStore('records').get('rows');r.onsuccess=()=>{resolve((r.result??[]).some((x:any)=>x.key.startsWith('terminal-tab:')&&x.value.includes('"kept":true')));db.close()}}}))).toBe(true)
 await page.reload();await expect(terminal(page).getByRole('complementary',{name:'Open evidence review'}).last()).toContainText('Partial result kept')
})
test('legacy gap card is usable on narrow and dark terminals; keeping it does not claim completion',async({page},info)=>{
 await openApp(page);await page.keyboard.press(`${MOD}+j`);await expect.poll(()=>page.evaluate(()=>!!(window as any).__oneTerm)).toBe(true)
 await page.evaluate(()=>{(window as any).__oneTerm.state.setState({status:'done',turns:[{n:1,status:'done',task:'Review SOP',startedAt:Date.now(),answer:'## Lücken in der Beleglage\n- **Implementierung:** `sopModel.ts` wurde nicht gelesen.\n- **Tests:** `sopRelease.test.ts` wurde nicht gelesen.\n- **Atlas:** Keine verknüpften Anforderungen.'}]})})
 const card=terminal(page).getByRole('complementary',{name:'Open evidence review'})
 await expect(card).toContainText('3 open checks')
 for(const width of [1440,390]){
  await page.evaluate(theme=>document.documentElement.setAttribute('data-theme',theme),width===1440?'light':'dark')
  await page.setViewportSize({width,height:900})
  await card.getByRole('button',{name:'Review missing evidence'}).click({trial:true})
  const box=await card.boundingBox();expect(box!.x).toBeGreaterThanOrEqual(0);expect(box!.x+box!.width).toBeLessThanOrEqual(width+1)
  await page.screenshot({path:info.outputPath(`evidence-${width}.png`)})
 }
 await card.getByRole('button',{name:'Keep partial result'}).click()
 await expect(terminal(page).locator('.term-activity')).toContainText('Partial result')
 await expect(card.locator('details')).not.toHaveAttribute('open','')
})
test('stopping a followup cannot clear its queue even after the model reports no gaps',async({page,context})=>{
 await openApp(page);await setKey(page);await page.keyboard.press(`${MOD}+j`)
 await expect.poll(()=>page.evaluate(()=>!!(window as any).__oneTerm)).toBe(true)
 await page.evaluate(gaps=>{(window as any).__oneTerm.state.setState({status:'done',turns:[{n:1,status:'done',task:'Review code',answer:'Partial',startedAt:Date.now(),evidence:{origin:'reported',gaps}}]})},Array.from({length:7},(_,i)=>gap(i)))
 let release!:()=>void;const held=new Promise<void>(resolve=>{release=resolve})
 await mockAgent(context,[call('empty','report_evidence_gaps',{gaps:[]}),async()=>{await held;return say('Done')()}])
 await terminal(page).getByRole('button',{name:'Review missing evidence'}).click()
 await expect.poll(()=>page.evaluate(()=>(window as any).__oneTerm.state.getState().steps.some((s:any)=>s.tool==='report_evidence_gaps'&&s.state==='ok'))).toBe(true)
 await terminal(page).getByRole('button',{name:'Stop',exact:true}).click()
 release()
 await expect.poll(()=>page.evaluate(()=>(window as any).__oneTerm.state.getState().status)).toBe('stopped')
 const turn=await page.evaluate(()=>(window as any).__oneTerm.state.getState().turns.at(-1))
 expect(turn.evidence.gaps).toHaveLength(7)
})
