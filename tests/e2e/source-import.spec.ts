import { test, expect, openApp, wsEval } from './fixtures'

test('source import requires review, keeps origin and original text, and supports undo', async ({ page }) => {
  await openApp(page)
  await page.locator('.sb').getByRole('button', { name: /^Import/ }).click()
  const dialog = page.getByRole('dialog')
  await dialog.locator('[data-source="external"]').click()
  await dialog.getByRole('button', { name: 'Paste text', exact: true }).click()
  await dialog.getByLabel('Title', { exact: true }).fill('EARS source reference')
  await dialog.getByLabel(/Source text/).fill('When a measurement starts, the system shall record the start time.\n\nExternal reference, not a confirmed project decision.')
  await dialog.getByLabel('Source URL (optional)').fill('https://example.com/ears?token=secret-example&edition=2')
  await dialog.getByLabel(/What is this source for/).fill('Evaluate our requirement wording.')
  const save = dialog.getByRole('button', { name: 'Import source', exact: true })
  await expect(save).toBeDisabled()
  await dialog.getByRole('checkbox').check()
  await expect(save).toBeEnabled()
  await page.screenshot({ path: '.shots/source-import.png' })
  await save.click()
  await expect(dialog.getByText(/Import complete/)).toBeVisible()
  const imported = await wsEval(page, s => Object.values(s.pages).find(p => p.title === 'EARS source reference'))
  expect(imported).toBeTruthy()
  expect(imported!.plain).toContain('record the start time')
  expect(imported!.plain).toContain('SHA-256')
  expect(imported!.plain).toContain('https://example.com/ears?edition=2')
  expect(JSON.stringify(imported)).not.toContain('secret-example')
  expect(imported!.plain).toContain('Not a confirmed project requirement')
  await dialog.getByRole('button', { name: 'Undo import', exact: true }).click()
  expect(await wsEval(page, (s, id) => !!s.pages[id], imported!.id)).toBe(false)
})

test('formatted clipboard retains tables, lists and links without executing or loading embedded content', async ({ page }) => {
  await openApp(page)
  await page.locator('.sb').getByRole('button', { name: /^Import/ }).click()
  const dialog = page.getByRole('dialog')
  await dialog.locator('[data-source="external"]').click()
  await dialog.getByRole('button', { name: 'Paste text', exact: true }).click()
  await dialog.getByLabel('Title', { exact: true }).fill('Reviewed clipboard reference')
  await dialog.getByLabel(/Source text/).evaluate(el => {
    const data = new DataTransfer()
    data.setData('text/html', '<p><strong>Source note</strong></p><table><tr><th>Field</th><th>Value</th></tr><tr><td>Mode</td><td>Simulation</td></tr></table><ul><li>First check</li></ul><a href="https://example.org/reference" onclick="window.__sourcePwned=1">Reference</a><img src="https://tracker.invalid/pixel"><script>window.__sourcePwned=1</script><p style="background:url(https://tracker.invalid/css)">Safe text</p>')
    data.setData('text/plain','Source note')
    el.dispatchEvent(new ClipboardEvent('paste', { bubbles:true,cancelable:true,clipboardData:data }))
  })
  const rich=dialog.getByRole('region',{name:'Formatted preview'})
  await expect(rich.locator('table tr')).toHaveCount(2)
  await expect(rich.locator('li')).toHaveText('First check')
  await expect(rich.locator('a')).toHaveAttribute('href','https://example.org/reference')
  expect(await rich.locator('img,script,[style],[onclick]').count()).toBe(0)
  expect(await page.evaluate(()=>(window as any).__sourcePwned)).toBeUndefined()
  await page.screenshot({path:'.shots/source-clipboard.png'})
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button',{name:'Import source',exact:true}).click()
  await expect(dialog.getByText(/Import complete/)).toBeVisible()
  const imported=await wsEval(page,s=>Object.values(s.pages).find(p=>p.title==='Reviewed clipboard reference'))
  const doc=JSON.stringify(imported!.content)
  expect(doc).toContain('"type":"table"')
  expect(doc).toContain('"type":"bulletList"')
  expect(doc).toContain('https://example.org/reference')
  expect(doc).not.toContain('tracker.invalid')
})

import {pdfBytes} from './helpers/files'

test('PDF source selection preserves original page number, file and hash; blank pages cannot be selected',async({page})=>{
  await openApp(page)
  await page.locator('.sb').getByRole('button',{name:/^Import/}).click()
  const dialog=page.getByRole('dialog')
  await dialog.locator('[data-source="external"]').click()
  await dialog.getByRole('button',{name:'PDF',exact:true}).click()
  await dialog.locator('input[type=file]').setInputFiles({name:'original-manual.pdf',mimeType:'application/pdf',buffer:Buffer.from(pdfBytes(2,'Original second page source',2))})
  await expect(dialog.getByRole('group',{name:/Select original pages/}).getByRole('checkbox')).toHaveCount(2)
  const pages=dialog.locator('.io-source__pages')
  await expect(pages.getByRole('checkbox').nth(0)).toBeDisabled()
  await expect(pages.getByRole('checkbox').nth(1)).toBeChecked()
  await expect(dialog.getByLabel(/Source text/)).toHaveValue(/\[Page 2\].*Original second page source/s)
  await page.screenshot({path:'.shots/source-pdf.png'})
  await dialog.getByRole('checkbox',{name:/Preview reviewed/}).check()
  await dialog.getByRole('button',{name:'Import source',exact:true}).click()
  await expect(dialog.getByText(/Import complete/)).toBeVisible()
  const imported=await wsEval(page,s=>Object.values(s.pages).find(p=>p.title==='original-manual'))
  expect(imported!.plain).toContain('Original pages: 2')
  expect(imported!.plain).toContain('SHA-256 (PDF bytes)')
  expect(JSON.stringify(imported!.content)).toContain('original-manual.pdf')
  const headings=(imported!.content?.content??[]).filter(n=>n.type==='heading').map(n=>JSON.stringify(n))
  expect(headings.join()).toContain('Page 2')
  expect(headings.join()).not.toContain('Page 1')
  await expect(dialog.getByRole('button',{name:'Review Atlas handoff',exact:true})).toBeVisible()
})
