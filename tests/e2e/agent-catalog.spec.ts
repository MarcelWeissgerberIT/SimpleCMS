test('catalog categories, text search, reset and the New agent dialog share all starters', async ({ page }) => {
  await openApp(page, '#/agents')
  const catalog = page.getByTestId('agx-catalog')
  await expect(catalog.locator('[data-recipe]')).toHaveCount(12)
  await expect(catalog.locator('.agx-catalog__group')).toHaveCount(6)
  await catalog.getByLabel('Category', { exact: true }).selectOption('coding')
  await expect(catalog.locator('[data-recipe]')).toHaveCount(2)
  await expect(catalog.locator('[data-recipe="test-plan"]')).toBeVisible()
  await catalog.getByRole('searchbox').fill('source code')
  await expect(catalog.locator('[data-recipe]')).toHaveCount(0)
  await expect(catalog.getByRole('status')).toContainText('No templates match')
  await catalog.getByRole('button', { name: 'Reset filters' }).click()
  await catalog.getByRole('searchbox').fill('Atlas')
  await expect(catalog.locator('[data-recipe]')).toHaveCount(1)
  await expect(catalog.locator('[data-recipe="atlas-triage"]')).toContainText('Select an MCP connection')
  expect(await wsEval(page, (s) => Object.keys(s.agents ?? {}).length)).toBe(0)
  await page.getByRole('button', { name: 'New agent', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'New agent' })
  await expect(dialog.locator('[data-recipe]')).toHaveCount(12)
  await dialog.getByLabel('Category', { exact: true }).selectOption('planning')
  await expect(dialog.locator('[data-recipe]')).toHaveCount(2)
  await dialog.locator('[data-recipe="ba"]').click()
  const editor = page.getByRole('dialog', { name: 'New agent' })
  await expect(editor.getByLabel('Name', { exact: true })).toHaveValue('BA · break down a work order')
  await expect(editor.getByLabel('Category', { exact: true })).toHaveValue('planning')
  await expect(editor.getByRole('radio', { name: 'Manual', exact: true })).toHaveAttribute('aria-checked', 'true')
})

test('a specialist needs sources; its editable category survives saving and reloading; legacy agents remain visible', async ({ page }) => {
  await openApp(page, '#/agents')
  await page.locator('[data-recipe="code-review"]').click()
  const dialog = page.getByRole('dialog', { name: 'New agent' })
  await expect(dialog.getByLabel('Category', { exact: true })).toHaveValue('coding')
  await dialog.getByRole('button', { name: 'Create agent' }).click()
  expect(await wsEval(page, (s) => Object.keys(s.agents ?? {}).length)).toBe(0)
  await dialog.getByRole('button', { name: 'Add page or database' }).click()
  await page.getByRole('menuitem', { name: /^Projects Database$/ }).click()
  await dialog.getByRole('button', { name: 'Create agent' }).click()
  await expect(dialog).toBeHidden()
  const saved = await wsEval(page, (s) => Object.values(s.agents ?? {})[0])
  expect(saved).toMatchObject({ category: 'coding', write: 'none', trigger: { type: 'manual' }, mcpServers: [], scope: { everything: false } })
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  const edit = page.getByRole('dialog')
  await edit.getByLabel('Category', { exact: true }).selectOption('planning')
  await edit.getByRole('button', { name: 'Save', exact: true }).click()
  await wsEval(page, (s, id) => {
    const old = s.agents[id]
    const { category, ...copy } = old
    s.upsertAgent({ ...copy, id: 'legacycatalog', name: 'Legacy helper' })
  }, saved.id)
  await flush(page)
  await reloadApp(page)
  await page.evaluate(() => { window.location.hash = '#/agents' })
  const own = page.locator('.agx-saved')
  await expect(own.locator('.agx-card')).toHaveCount(2)
  await own.getByLabel('Category', { exact: true }).selectOption('planning')
  await expect(own.locator('.agx-card')).toHaveCount(1)
  await expect(own.locator('.agx-card')).toContainText('Code review')
  await own.getByLabel('Category', { exact: true }).selectOption('custom')
  await expect(own.locator('.agx-card')).toContainText('Legacy helper')
  await expect(page.getByTestId('agx-catalog').locator('[data-recipe]')).toHaveCount(12)
  await own.getByRole('searchbox').fill('not present')
  await expect(own.getByRole('status')).toContainText('No saved agents match')
})

test('category sanitation keeps known values and drops unknown metadata', async ({ page }) => {
  await openApp(page, '#/agents')
  await wsEval(page, (s) => {
    const a = { id: 'validcat', name: 'Valid', category: 'knowledge', instructions: 'Report', trigger: { type: 'manual' }, scope: { everything: true, pages: [], databases: [] }, write: 'none', mcpServers: [], runner: 'browser', maxRunUsd: 0.5, enabled: false, createdAt: 1, updatedAt: 1 }
    s.upsertAgent(a)
    s.upsertAgent({ ...a, id: 'invalidcat', category: '__proto__' })
  })
  const categories = await wsEval(page, (s) => [s.agents.validcat.category, s.agents.invalidcat.category ?? null])
  expect(categories).toEqual(['knowledge', null])
})

