import { mkdirSync } from 'node:fs'
import { test, expect, openApp, waitForApp, signIn, email, wsEval, createWorkspace, newPerson, join, waitOnline, api } from './fixtures'

test('detached checkout stays local across reload, reviews conflicts and merges explicitly without copying device settings', async ({ page: owner, context }) => {
  test.setTimeout(180_000)
  const errors: string[] = []
  owner.on('pageerror', e => errors.push(e.message))
  await openApp(owner, 'local')
  await signIn(owner, email('checkout-owner'))
  const id = await createWorkspace(owner, 'ONE · Delivery workshop')
  await openApp(owner, id)
  await waitOnline(owner)
  const source = await wsEval(owner, s => {
    s.updateSettings({ userName: 'My private preferences', mcpServers: [{ id: 'myatlas', name: 'Atlas', url: 'https://private.invalid/mcp', token: '', enabled: false }] })
    const brief = s.createPage({ title: 'Workshop scope' })
    const tests = s.createPage({ title: 'Acceptance tests' })
    s.setContent(brief, { type: 'doc', content: [{ type: 'paragraph', attrs: { id: 'scope-block' }, content: [{ type: 'text', text: 'Requirement → decision → implementation → evidence.' }] }] }, 'e2e')
    const database = s.createDatabase({ title: 'Requirements' })
    const row = s.createPage({ title: 'First requirement', parentId: database, databaseId: database })
    return { brief, tests, database, row }
  })
  const originalFile = await owner.evaluate(async id => {
    const one = (window as any).__one
    const ref = await one.files.saveFile(new Blob(['Workshop evidence: offline PDF bytes.'], { type: 'application/pdf' }), 'evidence.pdf')
    one.workspace.getState().setContent(id, { type: 'doc', content: [{ type: 'fileBlock', attrs: { src: ref, name: 'evidence.pdf', size: 37 } }] }, 'e2e')
    return ref
  }, source.tests)
  const colleague = await newPerson(context)
  await signIn(colleague, email('checkout-colleague'))
  await join(owner, colleague, id)
  await openApp(colleague, id)
  await waitOnline(colleague)
  await expect.poll(() => wsEval(colleague, (s, id) => s.pages[id]?.title, source.brief)).toBe('Workshop scope')
  await owner.getByRole('button', { name: 'Cloud · Live', exact: true }).click()
  const checkout = owner.getByRole('dialog')
  await expect(checkout.getByRole('alert')).toContainText('Returning online does not synchronize')
  await expect(checkout.getByRole('button', { name: 'Check out and open locally' })).toBeDisabled()
  await checkout.getByRole('checkbox').check()
  await checkout.getByRole('button', { name: 'Check out and open locally' }).click()
  await owner.waitForURL(/w=local%3A/)
  await waitForApp(owner)
  const localUrl = owner.url()
  await expect(owner.getByRole('button', { name: 'Local · Checked out', exact: true })).toBeVisible()
  await expect(owner.locator('.checkout-banner')).toContainText('does not synchronize automatically')
  expect(await wsEval(owner, s => Object.keys(s.settings.mcpServers ?? {}).length)).toBe(0)
  const copiedFile = await wsEval(owner, (s, id) => s.pages[id].content.content[0].attrs.src, source.tests)
  expect(copiedFile).not.toBe(originalFile)
  expect(await owner.evaluate(async ref => (await (window as any).__one.files.getFile(ref)).blob.text(), copiedFile)).toContain('offline PDF bytes')
  await wsEval(owner, (s, ids) => {
    s.updatePage(ids.brief, { title: 'Local: narrowed workshop scope' })
    s.updatePage(ids.row, { title: 'Local: requirement ready' })
    s.setContent(ids.brief, { type: 'doc', content: [{ type: 'paragraph', attrs: { id: 'scope-block' }, content: [{ type: 'text', text: 'Local acceptance: one demonstrable end-to-end increment.', marks: [{ type: 'bold' }] }] }] }, 'e2e')
  }, source)
  const newLocalFile = await owner.evaluate(async id => {
    const one = (window as any).__one
    const ref = await one.files.saveFile(new Blob(['New local evidence.'], { type: 'application/pdf' }), 'local-evidence.pdf')
    const s = one.workspace.getState()
    s.setContent(id, { ...s.pages[id].content, content: [...s.pages[id].content.content, { type: 'fileBlock', attrs: { src: ref, name: 'local-evidence.pdf', size: 19 } }] }, 'e2e')
    return ref
  }, source.brief)
  await wsEval(colleague, (s, ids) => { s.updatePage(ids.brief, { title: 'Cloud: scope agreed with the team' }); s.updatePage(ids.tests, { title: 'Cloud: evidence checklist' }) }, source)
  await owner.reload(); await waitForApp(owner)
  expect(owner.url()).toBe(localUrl)
  expect(await wsEval(owner, (s, id) => s.pages[id].title, source.brief)).toBe('Local: narrowed workshop scope')
  expect(await wsEval(colleague, (s, id) => s.pages[id].title, source.row)).toBe('First requirement')
  await owner.getByRole('button', { name: 'Compare with cloud…', exact: true }).click()
  const review = owner.getByRole('dialog')
  await expect(review).toContainText('1 conflict')
  await expect(review.getByRole('button', { name: 'Merge selected changes' })).toBeDisabled()
  const conflict = review.locator('.checkout-change[data-conflict="true"]')
  await expect(conflict).toContainText('Local: narrowed workshop scope')
  await expect(conflict).toContainText('Cloud: scope agreed with the team')
  await expect(conflict).toContainText('Workshop scope')
  mkdirSync('.shots', { recursive: true })
  for (const theme of ['light', 'dark']) for (const width of [1440, 390]) {
    await owner.setViewportSize({ width, height: width === 390 ? 844 : 900 })
    await wsEval(owner, (s, theme) => s.updateSettings({ theme }), theme)
    await owner.waitForTimeout(300)
    await owner.screenshot({ path: `.shots/checkout-${width}-${theme}.png` })
    expect(await owner.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await owner.setViewportSize({ width: 1440, height: 900 })
  await wsEval(owner, s => s.updateSettings({ theme: 'light' }))
  // A late cloud edit invalidates the whole reviewed batch.
  await conflict.getByRole('button', { name: 'Keep cloud', exact: true }).click()
  await wsEval(colleague, (s, ids) => s.updatePage(ids.tests, { title: 'Cloud: evidence checklist v2' }), source)
  await expect.poll(async () => JSON.stringify((await api(owner, 'GET', `/api/workspaces/${id}/checkout`)).json)).toContain('checklist v2')
  await review.getByRole('button', { name: 'Merge selected changes', exact: true }).click()
  await expect(review.getByRole('alert')).toContainText('Nothing was merged')
  expect(await wsEval(colleague, (s, id) => s.pages[id].title, source.row)).toBe('First requirement')
  await review.getByRole('button', { name: 'Compare again', exact: true }).click()
  await expect(review).toContainText('1 conflict')
  await review.locator('.checkout-change[data-conflict="true"]').getByRole('button', { name: 'Keep cloud', exact: true }).click()
  await review.getByRole('button', { name: 'Merge selected changes', exact: true }).click()
  await expect(review).toContainText('Merged into the cloud')
  expect(await wsEval(owner, (s, id) => s.pages[id].title, source.brief)).toBe('Cloud: scope agreed with the team')
  expect(await wsEval(owner, (s, id) => s.pages[id].title, source.tests)).toBe('Cloud: evidence checklist v2')
  await expect.poll(() => wsEval(colleague, (s, id) => s.pages[id].title, source.row)).toBe('Local: requirement ready')
  expect(await wsEval(colleague, (s, id) => s.pages[id].title, source.tests)).toBe('Cloud: evidence checklist v2')
  expect(await wsEval(colleague, (s, id) => s.pages[id].title, source.brief)).toBe('Cloud: scope agreed with the team')
  await expect.poll(() => wsEval(colleague, (s, id) => JSON.stringify(s.pages[id].content), source.brief)).toContain('Local acceptance')
  expect(await colleague.evaluate(async ref => (await (window as any).__one.files.getFile(ref)).blob.text(), newLocalFile)).toBe('New local evidence.')
  await review.getByRole('button', { name: 'Close', exact: true }).last().click()
  await owner.getByRole('button', { name: 'Compare with cloud…', exact: true }).click()
  await expect(owner.getByRole('dialog')).toContainText('No local content changes to merge')
  await owner.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).last().click()
  await openApp(owner, id); await waitOnline(owner)
  expect(await wsEval(owner, s => s.settings.mcpServers[0]?.url)).toBe('https://private.invalid/mcp')
  await owner.goto(localUrl); await waitForApp(owner)
  await wsEval(owner, s => s.hydrate({ version: s.version, epoch: 'reset-lifetime', pages: {}, databases: {}, people: [], recent: [], settings: s.settings }))
  await expect(owner.locator('.checkout-banner')).toHaveCount(0)
  await expect(owner.getByRole('button', { name: 'Local · Checked out', exact: true })).toHaveCount(0)
  expect(await wsEval(colleague, (s, id) => s.pages[id].title, source.brief)).toBe('Cloud: scope agreed with the team')
  expect(errors).toEqual([])
  await colleague.context().close()
})
