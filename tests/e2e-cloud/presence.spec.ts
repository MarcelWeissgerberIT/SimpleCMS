import { test, expect, api, email, signIn, newPerson, openApp, waitOnline, wsEval, cloudEval, gotoPage, createWorkspace, join } from './fixtures'

test('workspace presence across pages and shared workspaces, private pages, errors and narrow layout', async ({ page, context }) => {
  test.setTimeout(150_000)
  await signIn(page, email('presence-owner'))
  const ws = await createWorkspace(page, 'Presence team')
  const second = await createWorkspace(page, 'Second shared team')
  const nadine = await newPerson(context)
  await signIn(nadine, email('presence-nadine'))
  await api(nadine, 'PATCH', '/api/me', { name: 'Nadine Test' })
  await join(page, nadine, ws)
  await join(page, nadine, second)
  await openApp(page, ws)
  await waitOnline(page)
  await openApp(nadine, ws)
  await waitOnline(nadine)
  const pageId = await wsEval(page, s => s.createPage({ title: 'Shared page' }))
  await gotoPage(page, pageId)
  const panel = page.getByRole('dialog', { name: 'Presence', exact: true })
  const openPresence = async () => {
    await page.getByTestId('workspace-presence').click()
    await expect(panel.getByText('Nadine Test', { exact: true })).toBeVisible()
  }
  await openPresence()
  await expect(page.getByTestId('workspace-presence')).toContainText('1')
  await page.screenshot({ path: 'test-results/presence-desktop.png' })
  await expect(panel.getByText('Connected in workspace', { exact: true })).toBeVisible()
  await gotoPage(nadine, pageId)
  await expect(panel.getByText('On this page', { exact: true })).toBeVisible()
  const privateId = await nadine.evaluate(async () => {
    const cloud = (window as any).__one.cloud
    return cloud.createPrivatePage({ title: 'Private details must never be shared' })
  })
  await gotoPage(nadine, privateId)
  await expect(panel.getByText('Connected in workspace', { exact: true })).toBeVisible()
  await expect(panel).not.toContainText('Private details')
  const snapshot = await api(page, 'GET', '/api/workspaces/presence')
  expect(JSON.stringify(snapshot.json)).not.toContain(privateId)
  // Another tab of this user must not appear as a colleague.
  const mine = await context.newPage()
  await openApp(mine, ws)
  await waitOnline(mine)
  await page.bringToFront()
  await panel.getByRole('button', { name: 'Close', exact: true }).click()
  await openPresence()
  await expect(panel.locator('li')).toHaveCount(1)
  // The observer stays in the first workspace while Nadine switches.
  await openApp(nadine, second)
  await waitOnline(nadine)
  await panel.getByRole('button', { name: 'Close', exact: true }).click()
  await openPresence()
  await expect(panel.locator('section').filter({ hasText: 'Second shared team' })).toContainText('Nadine Test')
  await expect(panel.locator('section').filter({ hasText: 'Presence team' })).toContainText('No other people connected.')
  // Keyboard, mobile and dark layout remain usable.
  await page.keyboard.press('Escape')
  await expect(panel).not.toBeVisible()
  await expect(page.getByTestId('workspace-presence')).toBeFocused()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await openPresence()
  const box = await panel.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  await page.screenshot({ path: 'test-results/presence-narrow.png' })
  // Failure is unknown, never an empty online list. The next opening can recover.
  await panel.getByRole('button', { name: 'Close', exact: true }).click()
  await page.route('**/api/workspaces/presence', r => r.fulfill({ status: 503, contentType: 'application/json', body: '{}' }))
  await page.getByTestId('workspace-presence').click()
  await expect(panel).toContainText('Presence cannot currently be checked.')
  await expect(panel.getByText('Nadine Test', { exact: true })).toHaveCount(0)
  await page.unroute('**/api/workspaces/presence')
  await panel.getByRole('button', { name: 'Close', exact: true }).click()
  await openPresence()
  const uid = await cloudEval(nadine, c => c.user.id)
  await api(page, 'DELETE', `/api/workspaces/${second}/members/${uid}`)
  await panel.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByTestId('workspace-presence').click()
  await expect(panel.getByText('Nadine Test', { exact: true })).toHaveCount(0)
  await mine.close()
})
