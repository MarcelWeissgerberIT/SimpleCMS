import { test, expect, openApp, waitForApp, signIn, email, wsEval, createWorkspace, newPerson, join, waitOnline } from './fixtures'

test('an additional local workspace copies to a team with paused agents and no personal connections, then synchronizes edits with a colleague', async ({ page: owner, context }) => {
  await openApp(owner, 'local')
  await signIn(owner, email('multi-workspace-owner'))
  await openApp(owner, 'local')
  await owner.locator('aside.sb .sb-head__ws').click()
  await owner.getByRole('menuitem', { name: 'New local workspace…' }).click()
  await owner.getByRole('textbox', { name: 'Workspace name', exact: true }).fill('Local delivery kit')
  await owner.getByRole('button', { name: 'Create and open', exact: true }).click()
  await owner.waitForURL(/w=local%3A/)
  await waitForApp(owner)
  const source = await wsEval(owner, s => {
    s.updateSettings({ userName: 'Personal only', mcpServers: [{ id: 'personal_mcp', name: 'atlas', url: 'https://personal.invalid/mcp', token: '', enabled: false }] })
    s.upsertAgent({ id: 'deliveryagent', name: 'Delivery helper', instructions: 'Read and report.', trigger: { type: 'manual' }, scope: { everything: true, pages: [], databases: [] }, write: 'none', output: null, mcpServers: ['atlas'], runner: 'browser', model: null, effort: null, maxRunUsd: 0.5, enabled: true, createdAt: Date.now(), updatedAt: Date.now() })
    const id = s.createPage({ title: 'Shared delivery brief' })
    s.setContent(id, { type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text: 'Acceptance criteria for the delivery.' }] }] }, 'e2e')
    return id
  })
  const target = await createWorkspace(owner, 'Shared delivery')
  await owner.evaluate(async id => (window as any).__one.cloud.uploadLocalWorkspace(id), target)
  expect(await wsEval(owner, s => s.settings.mcpServers[0].url)).toBe('https://personal.invalid/mcp')
  expect(await wsEval(owner, s => s.agents.deliveryagent.enabled)).toBe(true)
  const colleague = await newPerson(context)
  await signIn(colleague, email('multi-workspace-colleague'))
  await join(owner, colleague, target)
  await openApp(colleague, target)
  await waitOnline(colleague)
  await expect.poll(() => wsEval(colleague, (s, id) => s.pages[id]?.plain, source)).toContain('Acceptance criteria')
  await expect.poll(() => wsEval(colleague, s => s.agents.deliveryagent?.enabled)).toBe(false)
  expect(await wsEval(colleague, s => s.settings.mcpServers ?? [])).toEqual([])
  await openApp(owner, target)
  await waitOnline(owner)
  await wsEval(colleague, (s, id) => s.updatePage(id, { title: 'Brief reviewed together' }), source)
  await expect.poll(() => wsEval(owner, (s, id) => s.pages[id]?.title, source)).toBe('Brief reviewed together')
  await colleague.context().close()
})
